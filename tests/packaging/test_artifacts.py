def wheel_metadata(wheel: Path):
    with zipfile.ZipFile(wheel) as archive:
        metadata_name = next(
            name for name in archive.namelist() if name.endswith(".dist-info/METADATA")
        )
        return BytesParser().parsebytes(archive.read(metadata_name))


def wheel_entry_points(wheel: Path) -> str:
    with zipfile.ZipFile(wheel) as archive:
        entry_points_name = next(
            name for name in archive.namelist() if name.endswith(".dist-info/entry_points.txt")
        )
        return archive.read(entry_points_name).decode("utf-8")


def test_prohibited_member_scanner() -> None:
    assert prohibited_member_reason("polar-ble-sdk/protobuf/example.proto") == "SDK checkout"
    assert (
        prohibited_member_reason("polar_ble_tools/_generated/example_pb2.py")
        == "generated schema directory"
    )
    assert (
        prohibited_member_reason("polar_ble_tools/descriptor.desc")
        == "prohibited schema or compiled artifact"
    )
    assert prohibited_member_reason("tests/fixtures/private/device.json") == "private fixture path"
    assert (
        prohibited_member_reason("polar_ble_tools/sdk_tools/decoder_project/DecoderMain.kt") is None
    )
    assert (
        prohibited_member_reason("polar_ble_tools/sdk_tools/decoder_project/untrusted.kt")
        == "prohibited schema or compiled artifact"
    )
    assert prohibited_member_reason("README.md") is None


