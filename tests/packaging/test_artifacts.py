def test_clean_wheel_install_imports_and_shows_help_without_schema_activity(
    built_artifacts: list[Path], tmp_path: Path
) -> None:
    wheel = next(artifact for artifact in built_artifacts if artifact.suffix == ".whl")
    virtual_environment = tmp_path / "clean-venv"
    venv.EnvBuilder(with_pip=True).create(virtual_environment)
    python = virtual_environment / "bin" / "python"
    polar_ble = virtual_environment / "bin" / "polar-ble"
    cache_home = tmp_path / "cache"
    data_home = tmp_path / "data"
    environment = {
        **os.environ,
        "PYTHONNOUSERSITE": "1",
        "XDG_CACHE_HOME": str(cache_home),
        "XDG_DATA_HOME": str(data_home),
    }
    subprocess.run(
        [str(python), "-m", "pip", "install", str(wheel)],
        check=True,
        capture_output=True,
        text=True,
        env={**os.environ, "PYTHONNOUSERSITE": "1"},
    )
    subprocess.run(
        [str(python), "-c", "import polar_ble_tools"],
        check=True,
        capture_output=True,
        text=True,
        env=environment,
    )
    subprocess.run(
        [str(polar_ble), "--version"],
        check=True,
        capture_output=True,
        text=True,
        env=environment,
    )
    for command in ("pair", "connect", "discover", "sdk", "ftu", "raw", "passive", "bpb", "doctor"):
        subprocess.run(
            [str(polar_ble), command, "--help"],
            check=True,
            capture_output=True,
            text=True,
            env=environment,
        )
    assert not (data_home / "polar-ble-tools").exists()
    assert not cache_home.exists()


