def test_wheel_and_sdist_include_project_licence_and_notice(
    built_artifacts: list[Path],
) -> None:
    for artifact in built_artifacts:
        names = {Path(member).name for member in archive_member_names(artifact)}
        assert {"LICENSE", "NOTICE"}.issubset(names)


def test_wheel_metadata_uses_pep_639_and_declares_public_contract(
    built_artifacts: list[Path],
) -> None:
    wheel = next(artifact for artifact in built_artifacts if artifact.suffix == ".whl")
    metadata = wheel_metadata(wheel)

    assert metadata["Name"] == "polar-ble-tools"
    assert metadata["Version"] == project_version()
    assert metadata["Requires-Python"] == ">=3.11"
    assert metadata["License-Expression"] == "Apache-2.0"
    assert {"LICENSE", "NOTICE"}.issubset(metadata.get_all("License-File", []))
    assert set(metadata.get_all("Project-URL", [])) == {
        "Documentation, https://github.com/zyf0717/polar-ble-tools#readme",
        "Issues, https://github.com/zyf0717/polar-ble-tools/issues",
        "Source, https://github.com/zyf0717/polar-ble-tools",
    }
    assert "polar-ble = polar_ble_tools.commands.main:main" in wheel_entry_points(wheel)


