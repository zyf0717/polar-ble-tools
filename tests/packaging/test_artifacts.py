PROJECT_ROOT = Path(__file__).resolve().parents[2]


def project_version() -> str:
    with (PROJECT_ROOT / "pyproject.toml").open("rb") as metadata:
        return tomllib.load(metadata)["project"]["version"]


SKIPPED_SOURCE_DIRECTORIES = frozenset(
    {"dist", "build", "__pycache__", ".git", ".venv", ".pytest_cache"}
)
PRIVATE_PATH_COMPONENTS = frozenset({"private", "captures", "profiles"})
PROHIBITED_FILENAMES = frozenset(
    {"devices.yaml", "generation-plan.json", "generated-manifest.json"}
)
PROHIBITED_SUFFIXES = (
    ".rec",
    ".bpb",
    ".desc",
    ".proto",
    ".pb",
    "_pb2.py",
    "_pb2.pyi",
    ".jar",
    ".aar",
    ".class",
    ".kt",
    ".swift",
    ".framework",
    ".xcframework",
    ".zip",
)
PROHIBITED_CONTENT_MARKERS = (
    b"Generated by the protocol " + b"buffer compiler",
    b"Copyright (c) Polar " + b"Electro",
    b"Copyright Polar " + b"Electro",
)
PROJECT_OWNED_DECODER_TEMPLATES = frozenset(
    {
        "polar_ble_tools/sdk_tools/decoder_project/DecoderMain.kt",
        "polar_ble_tools/sdk_tools/decoder_project/build.gradle.kts",
        "polar_ble_tools/sdk_tools/decoder_project/settings.gradle.kts",
    }
)


def prohibited_member_reason(member: str) -> str | None:
    """Return the distribution-policy violation for an archive member, if any."""
    normalized = member.replace("\\", "/").lstrip("./")
    parts = tuple(part for part in normalized.split("/") if part)
    names = {part.casefold() for part in parts}
    if "polar-ble-sdk" in names:
        return "SDK checkout"
    if "_generated" in names:
        return "generated schema directory"
    if any(part in names for part in PRIVATE_PATH_COMPONENTS):
        return "private fixture path"
    if Path(normalized).name in PROHIBITED_FILENAMES:
        return "prohibited generated or private file"
    if any(normalized.endswith(template) for template in PROJECT_OWNED_DECODER_TEMPLATES):
        return None
    if normalized.endswith(PROHIBITED_SUFFIXES):
        return "prohibited schema or compiled artifact"
    return None


def source_member_names() -> list[str]:
    completed = subprocess.run(
        ["git", "ls-files", "-z"],
        cwd=PROJECT_ROOT,
        check=True,
        capture_output=True,
    )
    members = [name.decode("utf-8") for name in completed.stdout.split(b"\0") if name]
    return [
        name
        for name in members
        if not any(part in SKIPPED_SOURCE_DIRECTORIES for part in Path(name).parts)
    ]


def archive_member_names(artifact: Path) -> list[str]:
    if artifact.suffix == ".whl":
        with zipfile.ZipFile(artifact) as archive:
            return archive.namelist()
    with tarfile.open(artifact) as archive:
        return archive.getnames()


def archive_file_payloads(artifact: Path):
    if artifact.suffix == ".whl":
        with zipfile.ZipFile(artifact) as archive:
            for member in archive.infolist():
                if not member.is_dir():
                    yield member.filename, archive.read(member)
        return
    with tarfile.open(artifact) as archive:
        for member in archive.getmembers():
            if member.isfile():
                extracted = archive.extractfile(member)
                assert extracted is not None
                yield member.name, extracted.read()


def assert_no_prohibited_members(members: list[str]) -> None:
    violations = sorted(
        f"{member}: {reason}"
        for member in members
        if (reason := prohibited_member_reason(member)) is not None
    )
    assert not violations, "Prohibited distribution members:\n" + "\n".join(violations)


def assert_no_prohibited_content(artifact: Path) -> None:
    violations = sorted(
        f"{member}: {marker.decode('ascii')}"
        for member, payload in archive_file_payloads(artifact)
        for marker in PROHIBITED_CONTENT_MARKERS
        if marker.lower() in payload.lower()
    )
    assert not violations, "Prohibited distribution content:\n" + "\n".join(violations)


